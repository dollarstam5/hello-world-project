#!/usr/bin/env bash
set -euo pipefail

HOST="127.0.0.1"
PORT=""
BASE_URL=""
SERVER_LOG="${TMPDIR:-/tmp}/vitalis-e2e.log"
OUTPUT_DIR="${GITHUB_WORKSPACE:-.}/artifacts/mobile-smoke"
STORAGE_STATE_BASE="${TMPDIR:-/tmp}/vitalis-e2e-storage-${BASHPID}"
SERVER_PID=""
SCREENSHOT_TIMEOUT_SECONDS=45
SCREENSHOT_PID=""

terminate_process_group() {
  local pid="$1"
  [[ -n "$pid" ]] || return 0

  kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
  for _ in {1..5}; do
    if ! kill -0 "$pid" 2>/dev/null; then
      wait "$pid" 2>/dev/null || true
      return 0
    fi
    sleep 1
  done
  kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null || true
  wait "$pid" 2>/dev/null || true
}

run_screenshot() {
  local label="$1"
  shift

  echo "Capturing ${label}"
  setsid "$@" &
  SCREENSHOT_PID=$!
  local elapsed=0

  while kill -0 "$SCREENSHOT_PID" 2>/dev/null; do
    if (( elapsed >= SCREENSHOT_TIMEOUT_SECONDS )); then
      echo "ERROR: screenshot timed out after ${SCREENSHOT_TIMEOUT_SECONDS}s: ${label}" >&2
      terminate_process_group "$SCREENSHOT_PID"
      SCREENSHOT_PID=""
      return 124
    fi
    sleep 1
    elapsed=$((elapsed + 1))
  done

  local status=0
  wait "$SCREENSHOT_PID" || status=$?
  SCREENSHOT_PID=""
  if (( status != 0 )); then
    echo "ERROR: screenshot failed (${status}): ${label}" >&2
  fi
  return "$status"
}

cleanup() {
  if [[ -n "$SCREENSHOT_PID" ]]; then
    terminate_process_group "$SCREENSHOT_PID"
    SCREENSHOT_PID=""
  fi
  if [[ -n "$SERVER_PID" ]]; then
    # Wrangler may spawn child processes; terminate the entire dedicated session.
    kill -- "-$SERVER_PID" 2>/dev/null || kill "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
  fi
  rm -f "${STORAGE_STATE_BASE}-fr.json" "${STORAGE_STATE_BASE}-en.json"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

mkdir -p "$OUTPUT_DIR"

# Select a currently unused port for the local production Worker.
PORT="$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()')"
BASE_URL="http://${HOST}:${PORT}"

# Start with onboarding already completed so screenshots show each engine itself.
# Separate deterministic browser states exercise both supported interface languages.
for locale in fr en; do
  STORAGE_STATE="${STORAGE_STATE_BASE}-${locale}.json"
  printf '{"cookies":[],"origins":[{"origin":"%s","localStorage":[{"name":"vitalis.onboarding.v2","value":"1"},{"name":"eco.locale","value":"%s"}]}]}' \
    "$BASE_URL" "$locale" > "$STORAGE_STATE"
done

# Exercise the exact production output generated by the release build.
bun run build:check >/dev/null
test -s ".output/nitro.json"
test -s ".output/server/index.mjs"
test -s ".output/server/wrangler.json"

# Nitro's cloudflare preview wrapper currently fails before its preview handler
# initializes. Start the generated production Worker directly with Wrangler.
setsid bunx wrangler dev \
  --config ".output/server/wrangler.json" \
  --local \
  --ip "$HOST" \
  --port "$PORT" >"$SERVER_LOG" 2>&1 &
SERVER_PID=$!

for _ in {1..45}; do
  if curl --silent --fail "$BASE_URL/" >/dev/null; then
    break
  fi
  if ! kill -0 "$SERVER_PID" 2>/dev/null; then
    cat "$SERVER_LOG"
    exit 1
  fi
  sleep 1
done

if ! curl --silent --fail "$BASE_URL/" >/dev/null; then
  cat "$SERVER_LOG"
  exit 1
fi

# Check all six public entry routes at four viewport sizes in both supported locales.
for locale in fr en; do
  STORAGE_STATE="${STORAGE_STATE_BASE}-${locale}.json"
  for route in "/" "/flash" "/scan" "/reel" "/radar" "/vision"; do
    selector="#home-engines-title"
    case "$route" in
      "/flash") selector="main h1" ;;
      "/scan") selector="#scan-radius" ;;
      "/reel") selector=".reel-proximity" ;;
      "/radar") selector="main h1" ;;
      "/vision") selector="main h1" ;;
    esac

    for viewport in "360,800" "390,844" "412,915" "768,1024"; do
      output="$OUTPUT_DIR/vitalis-route-home-${viewport//,/-}-${locale}.png"
      case "$route" in
        "/flash") output="$OUTPUT_DIR/vitalis-route-flash-${viewport//,/-}-${locale}.png" ;;
        "/scan") output="$OUTPUT_DIR/vitalis-route-scan-${viewport//,/-}-${locale}.png" ;;
        "/reel") output="$OUTPUT_DIR/vitalis-route-reel-${viewport//,/-}-${locale}.png" ;;
        "/radar") output="$OUTPUT_DIR/vitalis-route-radar-${viewport//,/-}-${locale}.png" ;;
        "/vision") output="$OUTPUT_DIR/vitalis-route-vision-${viewport//,/-}-${locale}.png" ;;
      esac
      run_screenshot \
        "locale=${locale} route=${route} viewport=${viewport}" \
        bunx playwright screenshot \
        --browser=chromium \
        --viewport-size="$viewport" \
        --full-page \
        --load-storage="$STORAGE_STATE" \
        --wait-for-selector="$selector" \
        --wait-for-timeout=1800 \
        "$BASE_URL$route?__vitalis_smoke=1" \
        "$output" >/dev/null
      test -s "$output"
    done
  done
done

CHROMIUM_BIN="$(find "$HOME/.cache/ms-playwright" -type f -name chrome -print -quit)"
test -n "$CHROMIUM_BIN"
bun scripts/check-mobile-scroll.mjs "$CHROMIUM_BIN" "$BASE_URL"

echo "Production mobile E2E smoke validation passed for Home, Flash, Scan, En direct, Radar and Vision at four target viewports in French and English (48 screenshots), including four-viewport bottom-scroll clearance assertions for Flash and Scan."
